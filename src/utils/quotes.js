export function getRandomQuote(excludeIndex = -1) {
  let index;
  do {
    index = Math.floor(Math.random() * SUFI_MUSIC_QUOTES.length);
  } while (index === excludeIndex && SUFI_MUSIC_QUOTES.length > 1);
  return { ...SUFI_MUSIC_QUOTES[index], index };
}
